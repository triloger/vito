"""Environment and filesystem configuration.

Secrets come from the environment only (optionally via a local ``.env``).
Nothing secret is ever written to a committed file.
"""

from __future__ import annotations

import os
from dataclasses import dataclass
from pathlib import Path

try:  # pragma: no cover - optional dependency
    from dotenv import load_dotenv
except ImportError:  # pragma: no cover
    load_dotenv = None  # type: ignore[assignment]


def repo_root() -> Path:
    """Locate the project root.

    Order: ``$VITO_HOME``, then walk up from the current directory looking for
    ``config/policy.toml``, then the current directory.
    """
    env_home = os.environ.get("VITO_HOME")
    if env_home:
        return Path(env_home).expanduser().resolve()

    here = Path.cwd().resolve()
    for candidate in (here, *here.parents):
        if (candidate / "config" / "policy.toml").exists():
            return candidate
    return here


def load_env(root: Path | None = None) -> None:
    """Load ``<root>/.env`` into the process environment if present."""
    root = root or repo_root()
    env_file = root / ".env"
    if load_dotenv is not None and env_file.exists():
        load_dotenv(env_file, override=False)


@dataclass(frozen=True, slots=True)
class Credentials:
    api_key: str = ""
    api_secret: str = ""
    passphrase: str = ""
    demo: bool = False
    venue: str = "okx"

    @property
    def complete(self) -> bool:
        if self.venue == "binance":
            return bool(self.api_key and self.api_secret)
        return bool(self.api_key and self.api_secret and self.passphrase)

    def masked(self) -> str:
        if not self.api_key:
            return "absent"
        return f"{self.api_key[:4]}…{self.api_key[-4:]}"


def load_credentials() -> Credentials:
    load_env()
    venue = os.environ.get("VITO_EXCHANGE", "binance").strip().lower() or "binance"
    if venue == "okx":
        return Credentials(
            api_key=os.environ.get("VITO_OKX_API_KEY", "").strip(),
            api_secret=os.environ.get("VITO_OKX_API_SECRET", "").strip(),
            passphrase=os.environ.get("VITO_OKX_API_PASSPHRASE", "").strip(),
            demo=os.environ.get("VITO_OKX_DEMO", "0") == "1",
            venue="okx",
        )
    api_key = (
        os.environ.get("VITO_BINANCE_API_KEY")
        or os.environ.get("VITO_API_KEY")
        or os.environ.get("VITO_OKX_API_KEY")
        or ""
    ).strip()
    api_secret = (
        os.environ.get("VITO_BINANCE_API_SECRET")
        or os.environ.get("VITO_API_SECRET")
        or os.environ.get("VITO_OKX_API_SECRET")
        or ""
    ).strip()
    demo = (
        os.environ.get("VITO_BINANCE_DEMO")
        or os.environ.get("VITO_OKX_DEMO")
        or "0"
    ) == "1"
    return Credentials(
        api_key=api_key,
        api_secret=api_secret,
        passphrase=os.environ.get("VITO_OKX_API_PASSPHRASE", "").strip(),
        demo=demo,
        venue="binance",
    )


def write_env_credentials(
    api_key: str,
    api_secret: str,
    passphrase: str = "",
    *,
    demo: bool = False,
    venue: str = "binance",
    root: Path | None = None,
) -> Path:
    """Write ``.env`` with mode ``0600`` so secrets are never world-readable."""
    target = (root or repo_root()) / ".env"
    flag = "1" if demo else "0"
    content = (
        "# Generated by `vito setup` (mode 0600, gitignored)\n"
        f"VITO_EXCHANGE={venue.strip().lower()}\n"
        f"VITO_BINANCE_API_KEY={api_key.strip()}\n"
        f"VITO_BINANCE_API_SECRET={api_secret.strip()}\n"
        f"VITO_BINANCE_DEMO={flag}\n"
        f"VITO_OKX_API_KEY={api_key.strip()}\n"
        f"VITO_OKX_API_SECRET={api_secret.strip()}\n"
        f"VITO_OKX_API_PASSPHRASE={passphrase.strip()}\n"
        f"VITO_OKX_DEMO={flag}\n"
    )
    fd = os.open(target, os.O_WRONLY | os.O_CREAT | os.O_TRUNC, 0o600)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as fh:
            fh.write(content)
            fh.flush()
            os.fsync(fh.fileno())
        os.chmod(target, 0o600)
    except Exception:
        if target.exists():
            target.unlink()
        raise
    return target


@dataclass(frozen=True, slots=True)
class Settings:
    symbols: tuple[str, ...]
    spot_symbols: tuple[str, ...]
    expected_egress_ip: str = ""
    min_width: int = 80


DEFAULT_SYMBOLS = ("BTC-USDT-SWAP", "ETH-USDT-SWAP")
DEFAULT_SPOT = ("BTC-USDT", "ETH-USDT")


def load_settings(root: Path | None = None) -> Settings:
    """Load ``config/config.toml`` if present, else fall back to defaults."""
    import tomllib

    root = root or repo_root()
    path = root / "config" / "config.toml"
    if not path.exists():
        return Settings(symbols=DEFAULT_SYMBOLS, spot_symbols=DEFAULT_SPOT)

    raw = tomllib.loads(path.read_text())
    market = raw.get("market", {})
    ui = raw.get("ui", {})
    network = raw.get("network", {})
    return Settings(
        symbols=tuple(market.get("symbols", DEFAULT_SYMBOLS)),
        spot_symbols=tuple(market.get("spot_symbols", DEFAULT_SPOT)),
        expected_egress_ip=str(network.get("expected_egress_ip", "") or ""),
        min_width=int(ui.get("min_width", 80)),
    )
